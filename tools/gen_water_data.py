# Writes src/pbrt/water_data.cs: the refractive index of liquid water every 10 nm from 360 to 830 nm.
# usage: python3 gen_water_data.py OUT.cs Daimon-20.0C.csv Segelstein.csv
#   real part: Daimon and Masumura 2007 (20.0 C, 0.182-1.129 um), interpolated linearly
#   imaginary part: Segelstein 1981 (built on Pope and Fry 1997 in the visible), interpolated in the logarithm
# Both from refractiveindex.info
import sys, io
import numpy as np
def sections(path):
    text = open(path).read()
    parts = text.split('wl,k')
    n = np.loadtxt(io.StringIO(parts[0].replace('wl,n', '')), delimiter=',')
    k = np.loadtxt(io.StringIO(parts[1]), delimiter=',') if len(parts) > 1 and parts[1].strip() else None
    return n, k
out, daimon_path, segelstein_path = sys.argv[1:4]
daimon_n, _ = sections(daimon_path)
_, seg_k = sections(segelstein_path)
wl = np.arange(360, 831, 10)
n = np.interp(wl * 1e-3, daimon_n[:, 0], daimon_n[:, 1])
k = np.exp(np.interp(wl * 1e-3, seg_k[:, 0], np.log(np.maximum(seg_k[:, 1], 1e-30))))
def arr(name, values, fmt, comment):
    rows = []
    for i in range(0, len(values), 6):
        rows.append('            ' + ', '.join(fmt % v for v in values[i:i + 6]))
    return '        // ' + comment + '\n        public static readonly double[] ' + name + ' =\n        {\n' + ',\n'.join(rows) + '\n        };\n\n'
with open(out, 'w') as f:
    f.write('// (not in pbrt-v4) Generated by tools/gen_water_data.py. Do not edit.\n// Refractive index of liquid water: real part from Daimon and Masumura 2007 (20.0 C), imaginary part from Segelstein 1981 (refractiveindex.info)\n\nnamespace pbrt\n{\n    public static class WaterData\n    {\n')
    f.write(arr('Wavelength', wl.astype(float), '%.1f', 'Wavelength in nm'))
    f.write(arr('Real', n, '%.7f', 'Real part of the refractive index'))
    f.write(arr('Imaginary', k, '%.5e', 'Imaginary part of the refractive index (positive for absorption)'))
    f.write('    }\n}\n')
print('written', out)
