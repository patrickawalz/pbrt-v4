import re,sys
srcfile=sys.argv[1] if len(sys.argv)>1 else 'oslgram.cpp'
classname=sys.argv[2] if len(sys.argv)>2 else 'OslGramTables'
outfile=sys.argv[3] if len(sys.argv)>3 else 'oslgram_tables.cs'
src=open(srcfile).read()
def arr(name):
    m=re.search(r'static const \w+ '+name+r'\[\] =\s*\{(.*?)\};',src,re.S)
    return [int(x) for x in re.findall(r'-?\d+',m.group(1))]
def const(name):
    return int(re.search(r'#define '+name+r'\s+\(?(-?\d+)\)?',src).group(1))
names=['yytranslate','yyr1','yyr2','yypact','yydefact','yypgoto','yydefgoto','yytable','yycheck']
out=['// OSL port: the LALR(1) tables that bison generates from the grammar (GENERATED by tools/osl/gen_oslgram_tables.py from bison 3.8.2 output; do not edit)','',
'namespace OSL','{','    namespace pvt','    {','        public static class '+classname+'','        {']
for c in ['YYFINAL','YYLAST','YYNTOKENS','YYMAXUTOK','YYPACT_NINF','YYTABLE_NINF','YYNRULES','YYNSTATES']:
    out.append('            public const int %s = %d;'%(c,const(c)))
out.append('')
for n in names:
    a=arr(n)
    out.append('            public static readonly short[] %s ='%n)
    out.append('            {')
    for i in range(0,len(a),16):
        out.append('                '+', '.join(str(x) for x in a[i:i+16])+',')
    out.append('            };')
    out.append('')
out+=['        }','    }','}']
open(outfile,'w').write('\n'.join(out)+'\n')
print({n:len(arr(n)) for n in names})
