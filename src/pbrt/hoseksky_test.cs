        [TEST("HosekSky", "OtherStarIsTheAuthors")]
        public static void OtherStarIsTheAuthors()
        {
            int rows = ReferenceStar.GetLength(0);
            EXPECT_GT(rows, 100);
            int discs = 0;
            for (int row = 0; row < rows; ++row)
            {
                double[] albedo = new double[HosekSkyModel.Bands];
                for (int band = 0; band < HosekSkyModel.Bands; ++band)
                {
                    albedo[band] = ReferenceStar[row, 2];
                }
                HosekSkyModel model = new HosekSkyModel(ReferenceStar[row, 0], ReferenceStar[row, 1], albedo, ReferenceStar[row, 3], ReferenceStar[row, 4]);
                double radiance = model.Radiance(ReferenceStar[row, 5], ReferenceStar[row, 6], ReferenceStar[row, 7]);
                EXPECT_NEAR(ReferenceStar[row, 8], radiance, 1e-11 * Math.Abs(ReferenceStar[row, 8]) + 1e-300, "row " + row);
                EXPECT_NEAR(ReferenceStar[row, 9], model.DiscRadius, 1e-12 * ReferenceStar[row, 9], "row " + row);
                double solar = model.SolarRadiance(ReferenceStar[row, 0], ReferenceStar[row, 10], ReferenceStar[row, 7]);
                EXPECT_NEAR(ReferenceStar[row, 11], solar, 1e-9 * Math.Abs(ReferenceStar[row, 11]) + 1e-10, "row " + row);
                discs += solar > 0 ? 1 : 0;
            }
            EXPECT_GT(discs, rows / 2);
        }

        // The light of another star: a star of the sun's temperature and of the intensity 1 lights a level ground about as
        // the sun does, and a star twice as intense twice as much, with the disc of twice the solid angle; the light is
        // found by its own samples as by uniform directions
        [TEST("HosekSky", "OtherStarLight")]
        public static void OtherStarLight()
        {
            Vector3f zenith = new Vector3f(0, 0, 1);
            double elevation = 40 * Math.PI / 180;
            Vector3f toSun = new Vector3f(0, (Float)Math.Cos(elevation), (Float)Math.Sin(elevation));
            double[] albedo = new double[HosekSkyModel.Bands];
            LightSampleContext ctx = new LightSampleContext(new Point3fi(new Point3f(0, 0, 0)), new Normal3f(0, 0, 0), new Normal3f(0, 0, 0));
            double[] irradiance = new double[5];
            double[] temperatures = { 0, 5800, 5800, 3500, 9000 };
            double[] intensities = { 1, 1, 2, 1, 1 };
            for (int k = 0; k < 5; ++k)
            {
                HosekSkyLight light = new HosekSkyLight(zenith, toSun, 3, albedo, 1, true, false, false, false, temperatures[k], intensities[k]);
                light.Preprocess(new Bounds3f(new Point3f(-1, -1, -1), new Point3f(1, 1, 1)));
                RNG rng = new RNG(61);
                int count = 300000;
                double sum = 0, squares = 0;
                for (int i = 0; i < count; ++i)
                {
                    SampledWavelengths lambda = SampledWavelengths.SampleVisible(rng.Uniform<Float>());
                    pstd.optional<LightLiSample> sample = light.SampleLi(ctx, new Point2f(rng.Uniform<Float>(), rng.Uniform<Float>()), lambda);
                    if ((bool)sample)
                    {
                        LightLiSample ls = sample.value();
                        EXPECT_NEAR(1.0, light.PDF_Li(ctx, ls.wi) / ls.pdf, 1e-4);
                        SampledSpectrum seen = light.Le(new Ray(new Point3f(0, 0, 0), ls.wi), lambda);
                        EXPECT_NEAR(1.0, (seen[0] + 1e-9) / (ls.L[0] + 1e-9), 5e-3);
                        // (the luminous irradiance of the level ground)
                        double v = (ls.L * Spectra.Y().Sample(lambda) / lambda.PDF()).Average() * ls.wi.z / ls.pdf;
                        sum += v;
                        squares += v * v;
                    }
                }
                irradiance[k] = sum / count;
                double error = Math.Sqrt(Math.Max(0.0, squares / count - irradiance[k] * irradiance[k]) / count);
                Console.WriteLine("star " + temperatures[k] + " K, intensity " + intensities[k] + ": luminous irradiance " + irradiance[k] + " +- " + error);
                EXPECT_LT(error, 0.01 * irradiance[k]);
            }
            // (the blackbody of 5800 K stands for the sun to a few per cent)
            EXPECT_NEAR(1.0, irradiance[1] / irradiance[0], 0.08);
            EXPECT_NEAR(2.0, irradiance[2] / irradiance[1], 0.03);
            // (stars of other colours send about as much in all; in luminance within a factor)
            EXPECT_GT(irradiance[3] / irradiance[0], 0.4);
            EXPECT_LT(irradiance[3] / irradiance[0], 1.5);
            EXPECT_GT(irradiance[4] / irradiance[0], 0.4);
            EXPECT_LT(irradiance[4] / irradiance[0], 1.5);
        }

        [TEST("HosekSky", "ModelIsTheAuthors")]
        public static void ModelIsTheAuthors()
        {
            int rows = Reference.GetLength(0);
            EXPECT_GT(rows, 100);
            for (int row = 0; row < rows; ++row)
            {
                double[] albedo = new double[HosekSkyModel.Bands];
                for (int band = 0; band < HosekSkyModel.Bands; ++band)
                {
                    albedo[band] = Reference[row, 2];
                }
                HosekSkyModel model = new HosekSkyModel(Reference[row, 0], Reference[row, 1], albedo);
                double radiance = model.Radiance(Reference[row, 3], Reference[row, 4], Reference[row, 5]);
                EXPECT_NEAR(Reference[row, 6], radiance, 1e-11 * Math.Abs(Reference[row, 6]) + 1e-300, "row " + row);
                double solar = model.SolarRadiance(Reference[row, 0], Reference[row, 7], Reference[row, 5]);
                // (the authors' value is a difference of two sums: to the last digits of the larger)
                EXPECT_NEAR(Reference[row, 8], solar, 1e-9 * Math.Abs(Reference[row, 8]) + 1e-10, "row " + row);
            }
        }

        private static HosekSkyLight Sky(bool sun, bool ground, double elevationDegrees, double turbidity, bool mixture = false)
        {
            double elevation = elevationDegrees * Math.PI / 180;
            Vector3f zenith = Normalize(new Vector3f(0.2f, -0.3f, 1));
            Vector3f side = Normalize(Cross(zenith, new Vector3f(1, 0, 0)));
            Vector3f toSun = Normalize((Float)Math.Sin(elevation) * zenith + (Float)Math.Cos(elevation) * side);
            double[] albedo = new double[HosekSkyModel.Bands];
            for (int band = 0; band < HosekSkyModel.Bands; ++band)
            {
                albedo[band] = 0.1 + 0.05 * band;
            }
            HosekSkyLight light = new HosekSkyLight(zenith, toSun, turbidity, albedo, 1, sun, ground, mixture, false);
            light.Preprocess(new Bounds3f(new Point3f(-1, -1, -1), new Point3f(1, 1, 1)));
            return light;
        }

        // The light: the density that is given is that of the samples (the mean of one over it is the sphere, and so are its
        // parts toward and away from the sun), the radiance of a sample is that of a ray in its direction, and the light
        // over the sphere by its own samples is the light by uniform directions and, for the disc, by its own cone
        [TEST("HosekSky", "LightSamplesWhatItEmits")]
        public static void LightSamplesWhatItEmits()
        {
            SamplesWhatItEmits(false, 23, 3.5);
        }

        // The same with the sky sampled by the truncated Gaussian mixtures, at a sky of the fits, between two of them, and
        // beyond their range (the turbidity 1; a sun at the horizon and at the zenith)
        [TEST("HosekSky", "MixtureSamplesWhatItEmits")]
        public static void MixtureSamplesWhatItEmits()
        {
            SamplesWhatItEmits(true, 23, 3.5);
            SamplesWhatItEmits(true, 0.5, 1.0);
            SamplesWhatItEmits(true, 90, 10.0);
        }

        private static void SamplesWhatItEmits(bool mixture, double elevationDegrees, double turbidity)
        {
            foreach (bool sun in new bool[] { false, true })
            {
                foreach (bool ground in new bool[] { false, true })
                {
                    HosekSkyLight light = Sky(sun, ground, elevationDegrees, turbidity, mixture);
                    LightSampleContext ctx = new LightSampleContext(new Point3fi(new Point3f(0, 0, 0)), new Normal3f(0, 0, 0), new Normal3f(0, 0, 0));
                    SampledWavelengths lambda = SampledWavelengths.SampleVisible(0.31f);
                    RNG rng = new RNG(31);
                    int count = 400000;
                    double sphere = 0, sphereSquares = 0, own = 0, ownSquares = 0, uniform = 0, uniformSquares = 0, largest = 0;
                    for (int i = 0; i < count; ++i)
                    {
                        pstd.optional<LightLiSample> sample = light.SampleLi(ctx, new Point2f(rng.Uniform<Float>(), rng.Uniform<Float>()), lambda);
                        if ((bool)sample)
                        {
                            LightLiSample ls = sample.value();
                            EXPECT_NEAR(1.0, light.PDF_Li(ctx, ls.wi) / ls.pdf, 1e-4);
                            SampledSpectrum seen = light.Le(new Ray(new Point3f(0, 0, 0), ls.wi), lambda);
                            // (to a part in a few hundred: at the limb of the solar disc the radiance is steep in the direction, which a ray holds
                            // in single precision)
                            EXPECT_NEAR(1.0, seen[0] / ls.L[0], 5e-3);
                            double v = ls.L[0] / ls.pdf;
                            own += v;
                            ownSquares += v * v;
                        }
                        // (uniform directions: one over the density of the light there is the measure of the sphere)
                        Vector3f w = SampleUniformSphere(new Point2f(rng.Uniform<Float>(), rng.Uniform<Float>()));
                        Float pdf = light.PDF_Li(ctx, w);
                        double u = light.Le(new Ray(new Point3f(0, 0, 0), w), lambda)[0] * 4 * Math.PI;
                        // (no direction with light is without a density; the largest weight a sample can have)
                        if (u > 0)
                        {
                            EXPECT_GT(pdf, 0);
                            largest = Math.Max(largest, u / (4 * Math.PI) / pdf);
                        }
                        uniform += u;
                        uniformSquares += u * u;
                        if ((bool)sample)
                        {
                            double s = 1.0 / sample.value().pdf;
                            sphere += s;
                            sphereSquares += s * s;
                        }
                    }
                    own /= count;
                    uniform /= count;
                    sphere /= count;
                    double ownError = Math.Sqrt(Math.Max(0.0, ownSquares / count - own * own) / count);
                    double uniformError = Math.Sqrt(Math.Max(0.0, uniformSquares / count - uniform * uniform) / count);
                    double sphereError = Math.Sqrt(Math.Max(0.0, sphereSquares / count - sphere * sphere) / count);
                    Console.WriteLine((mixture ? "mixture, " : "table, ") + elevationDegrees + " deg, turbidity " + turbidity + ", sun " + sun + " ground " + ground + ": by the light's samples " + own + " +- " + ownError +
                                      ", by uniform directions " + uniform + " +- " + uniformError + "; the sphere " + sphere + " +- " + sphereError +
                                      "; largest weight over the mean " + largest / own);
                    if (!sun)
                    {
                        EXPECT_LT(Math.Abs(own - uniform), 4 * Math.Sqrt(ownError * ownError + uniformError * uniformError));
                    }
                    if (ground || true)
                    {
                        // (the samples that carry no light, below the horizon without a ground, are not counted: with a ground
                        // every direction carries light)
                        EXPECT_LT(Math.Abs(sphere - (ground ? 4 : 2) * Math.PI), 4 * sphereError + 1e-3);
                    }
                    EXPECT_LT(ownError, (mixture ? 0.05 : 0.02) * own);
                }
            }
        }

        // The solar disc: by the samples of the light, the light of a sky with the sun less that of the sky alone is the
        // radiance of the disc integrated over it by rings
        [TEST("HosekSky", "SolarDisc")]
        public static void SolarDisc()
        {
            double elevationDegrees = 35, turbidity = 2.5;
            HosekSkyLight with = Sky(true, false, elevationDegrees, turbidity), without = Sky(false, false, elevationDegrees, turbidity);
            LightSampleContext ctx = new LightSampleContext(new Point3fi(new Point3f(0, 0, 0)), new Normal3f(0, 0, 0), new Normal3f(0, 0, 0));
            SampledWavelengths lambda = SampledWavelengths.SampleVisible(0.31f);
            double[] albedo = new double[HosekSkyModel.Bands];
            for (int band = 0; band < HosekSkyModel.Bands; ++band)
            {
                albedo[band] = 0.1 + 0.05 * band;
            }
            HosekSkyModel model = new HosekSkyModel(elevationDegrees * Math.PI / 180, turbidity, albedo);
            double expected = 0;
            int rings = 4000;
            double cosRadius = Math.Cos(HosekSkyModel.SolarRadius);
            for (int ring = 0; ring < rings; ++ring)
            {
                double cosGamma = 1 - (ring + 0.5) / rings * (1 - cosRadius);
                // (the elevation over the disc is that of its centre to within its radius: the radiance changes little)
                expected += model.SolarRadiance(elevationDegrees * Math.PI / 180, Math.Acos(cosGamma), lambda[0]) * 2 * Math.PI * (1 - cosRadius) / rings;
            }
            RNG rng = new RNG(33);
            int count = 400000;
            double sumWith = 0, sumWithout = 0, squares = 0;
            for (int i = 0; i < count; ++i)
            {
                Point2f u = new Point2f(rng.Uniform<Float>(), rng.Uniform<Float>());
                pstd.optional<LightLiSample> a = with.SampleLi(ctx, u, lambda), b = without.SampleLi(ctx, u, lambda);
                double va = (bool)a ? a.value().L[0] / a.value().pdf : 0, vb = (bool)b ? b.value().L[0] / b.value().pdf : 0;
                sumWith += va;
                sumWithout += vb;
                squares += va * va + vb * vb;
            }
            double difference = (sumWith - sumWithout) / count;
            double error = Math.Sqrt(squares / count / count);
            Console.WriteLine("the disc by the samples " + difference + " +- " + error + ", by rings " + expected);
            EXPECT_LT(Math.Abs(difference - expected), 4 * error + 0.01 * expected);
        }

        // The polarisation of the sky by the heuristic of Wilkie et al.: none at the sun, most near 90 degrees from it, less in
        // a hazier sky, never above one; and the light as the integrators ask for it is polarised at right angles to the plane
        // of the sun and the direction
        [TEST("HosekSky", "Polarisation")]
        public static void Polarisation()
        {
            double[] albedo = new double[HosekSkyModel.Bands];
            Vector3f zenith = new Vector3f(0, 0, 1);
            double elevation = 30 * Math.PI / 180;
            Vector3f toSun = new Vector3f(0, (Float)Math.Cos(elevation), (Float)Math.Sin(elevation));
            double previous = 2;
            foreach (double turbidity in new double[] { 2.5, 4, 7, 10 })
            {
                HosekSkyLight light = new HosekSkyLight(zenith, toSun, turbidity, albedo, 1, false, false, false, true);
                EXPECT_NEAR(0.0, light.DegreeOfPolarisation(Math.PI / 2 - elevation, 0), 1e-12);
                double largest = 0, largestGamma = 0;
                for (int i = 1; i < 180; ++i)
                {
                    // (along the sun's vertical, through the zenith)
                    double gamma = i * Math.PI / 180;
                    double theta = Math.Abs(Math.PI / 2 - elevation - gamma);
                    if (theta >= Math.PI / 2)
                    {
                        continue;
                    }
                    double degree = light.DegreeOfPolarisation(theta, gamma);
                    EXPECT_GE(degree, 0);
                    EXPECT_LE(degree, 1);
                    if (degree > largest)
                    {
                        largest = degree;
                        largestGamma = gamma;
                    }
                }
                Console.WriteLine("turbidity " + turbidity + ": largest degree " + largest + " at " + largestGamma * 180 / Math.PI + " degrees from the sun");
                EXPECT_GT(largestGamma, 70 * Math.PI / 180);
                EXPECT_LT(largestGamma, 110 * Math.PI / 180);
                EXPECT_LT(largest, previous);
                previous = largest;
            }

            HosekSkyLight sky = new HosekSkyLight(zenith, toSun, 3, albedo, 1, false, false, false, true);
            sky.Preprocess(new Bounds3f(new Point3f(-1, -1, -1), new Point3f(1, 1, 1)));
            SampledWavelengths lambda = SampledWavelengths.SampleVisible(0.4f);
            SampledSpectrum scalar = new SampledSpectrum(2.0f);
            // (a direction 90 degrees from the sun, to the side of it)
            Vector3f toSky = Normalize(Cross(toSun, new Vector3f(0.2f, 0, 1)));
            if (toSky.z < 0)
            {
                toSky = -toSky;
            }
            double expected = sky.DegreeOfPolarisation(Math.Acos(toSky.z), Math.PI / 2);
            EXPECT_GT(expected, 0.1);
            PolarisedLightSystem.Light found = PolarisedEmission.AtInfinity(sky, -toSky, lambda, scalar);
            Vector3f across = Normalize(Cross(toSky, toSun));
            StokesVector along = found.RepresentInDirection(-toSky, across).ToStokesVector();
            EXPECT_NEAR(2.0, along.s0[0], 1e-5);
            EXPECT_NEAR(2.0 * expected, along.s1[0], 1e-5);
            EXPECT_NEAR(0.0, along.s2[0], 1e-5);
            EXPECT_NEAR(0.0, along.s3[0], 1e-5);
            // (in the frame turned a quarter the sign is the other)
            StokesVector turned = found.RepresentInDirection(-toSky, Normalize(Cross(-toSky, across))).ToStokesVector();
            EXPECT_NEAR(-2.0 * expected, turned.s1[0], 1e-5);
            // (the same by a sample of the light; and none below the horizon or without the option)
            Interaction point = new Interaction(new Point3f(0, 0, 0), new MediumInterface());
            StokesVector sampled = PolarisedEmission.AtPoint(sky, point, -toSky, lambda, scalar).RepresentInDirection(-toSky, across).ToStokesVector();
            EXPECT_NEAR(2.0 * expected, sampled.s1[0], 1e-5);
            EXPECT_FALSE(PolarisedEmission.AtInfinity(sky, new Vector3f(0, 0, 1), lambda, scalar).IsPolarised());
            HosekSkyLight plain = new HosekSkyLight(zenith, toSun, 3, albedo, 1, false, false, false, false);
            EXPECT_FALSE(PolarisedEmission.AtInfinity(plain, -toSky, lambda, scalar).IsPolarised());
        }
    }
