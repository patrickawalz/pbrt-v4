        public static pstd.vector<Shape> Create(Transform renderFromObject, Transform objectFromRender, bool reverseOrientation, ParameterDictionary parameters,
                                                FileLoc loc, Allocator alloc)
        {
            pstd.vector<Shape> shapes = new pstd.vector<Shape>();
            Float scale = parameters.GetOneFloat("scale", 1);
            if (!(scale > 0))
            {
                pbrt.Error(loc, "teapot: \"scale\" must be positive.");
                return shapes;
            }
            bool bottom = parameters.GetOneBool("bottom", false);
            bool lid = parameters.GetOneBool("lid", true);
            Transform placed = renderFromObject * pbrt.Scale(scale, scale, scale);
            Transform placedInverse = pbrt.Scale(1 / scale, 1 / scale, 1 / scale) * objectFromRender;
            for (int patch = 0; patch < PatchCount; ++patch)
            {
                if ((patch >= 28 && !bottom) || (patch >= 20 && patch < 28 && !lid))
                {
                    continue;
                }
                List<ParsedParameter> list = new List<ParsedParameter>();
                ParsedParameter type = new ParsedParameter(null);
                type.type = "string";
                type.name = "type";
                type.strings.push_back("bicubic");
                list.Add(type);
                ParsedParameter points = new ParsedParameter(null);
                points.type = "point3";
                points.name = "P";
                // P[v * 4 + u]; the table lists row r, column c at 4 r + c, and the transposed grid has the normals outward
                for (int v = 0; v < 4; ++v)
                {
                    for (int u = 0; u < 4; ++u)
                    {
                        int index = Table[16 * patch + 4 * v + u] * 3;
                        points.floats.push_back(Vertices[index]);
                        points.floats.push_back(Vertices[index + 1]);
                        points.floats.push_back(Vertices[index + 2]);
                    }
                }
                list.Add(points);
                pstd.vector<Shape> made = Patches.CreateMesh("patch", placed, placedInverse, reverseOrientation, new ParameterDictionary(list, RGBColorSpace.sRGB), loc, alloc);
                for (int i = 0; i < (int)made.size(); ++i)
                {
                    shapes.push_back(made[i]);
                }
            }
            return shapes;
        }
