        /// \brief Debug print
        public void print()
        {
            Console.Write("patchTable ({0})\n", GetHashCode());
            Console.Write("  numPatches = {0}\n", GetNumPatchesTotal());

            for (int i = 0; i < GetNumPatchArrays(); ++i)
            {
                Console.Write("  patchArray {0}:\n", i);
                PatchArray pa = getPatchArray(i);
                pa.print();
            }
        }

