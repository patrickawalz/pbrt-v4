using System;
using System.Collections.Generic;
using OpenSubdiv.Sdc;
using OpenSubdiv.Vtr;
using OpenSubdiv.Far.Internal;

using IndexArray = OpenSubdiv.Vtr.Array<int>;
using ConstIndexArray = OpenSubdiv.Vtr.ConstArray<int>;
using PatchParamArray = OpenSubdiv.Vtr.Array<OpenSubdiv.Far.PatchParam>;
using ConstPatchParamArray = OpenSubdiv.Vtr.ConstArray<OpenSubdiv.Far.PatchParam>;

namespace OpenSubdiv.Far
{
    ///
    /// \brief Container for arrays of parametric patches
    ///
    /// PatchTable contain topology and parametric information about the patches
    /// generated by the Refiner.
    ///
    public class PatchTable
    {
        /// \brief A PatchHandle is a set of identifiers that locates a patch in the table
        public class PatchHandle
        {
            //  friends: PatchTable, PatchMap (public in C#)
            public int arrayIndex; // Array index of the patch
            public int patchIndex; // Absolute Index of the patch
            public int vertIndex;  // Relative offset to the first CV of the patch in array
        }

        //  Copy constructor (deep copies the stencil tables, as in the C++ source -- note that the
        //  C++ copy constructor does not copy _varyingVerts, which is preserved here)
        public PatchTable(PatchTable src)
        {
            _maxValence = src._maxValence;
            _numPtexFaces = src._numPtexFaces;
            _patchArrays = new StdVector<PatchArray>(src._patchArrays);
            _patchVerts = new StdVector<int>(src._patchVerts);
            _paramTable = new StdVector<PatchParam>(src._paramTable);
            _quadOffsetsTable = new StdVector<uint>(src._quadOffsetsTable);
            _vertexValenceTable = new StdVector<int>(src._vertexValenceTable);
            _localPointStencils = src._localPointStencils;
            _localPointVaryingStencils = src._localPointVaryingStencils;
            _varyingDesc = src._varyingDesc;
            _varyingVerts = new StdVector<int>();
            _fvarChannels = new StdVector<FVarPatchChannel>();
            for (int i = 0; i < src._fvarChannels.Count; ++i)
            {
                _fvarChannels.PushBack(new FVarPatchChannel(src._fvarChannels[i]));
            }
            _localPointFaceVaryingStencils = new StdVector<StencilTablePtr>();
            _sharpnessIndices = new StdVector<int>(src._sharpnessIndices);
            _sharpnessValues = new StdVector<float>(src._sharpnessValues);
            _isUniformLinear = src._isUniformLinear;
            _vertexPrecisionIsDouble = src._vertexPrecisionIsDouble;
            _varyingPrecisionIsDouble = src._varyingPrecisionIsDouble;
            _faceVaryingPrecisionIsDouble = src._faceVaryingPrecisionIsDouble;

            if (src._localPointStencils)
            {
                if (src._vertexPrecisionIsDouble)
                {
                    _localPointStencils.Set(
                        new StencilTableReal<double>(src._localPointStencils.Get<double>()));
                }
                else
                {
                    _localPointStencils.Set(
                        new StencilTableReal<float>(src._localPointStencils.Get<float>()));
                }
            }
            if (src._localPointVaryingStencils)
            {
                if (src._varyingPrecisionIsDouble)
                {
                    _localPointVaryingStencils.Set(
                        new StencilTableReal<double>(src._localPointVaryingStencils.Get<double>()));
                }
                else
                {
                    _localPointVaryingStencils.Set(
                        new StencilTableReal<float>(src._localPointVaryingStencils.Get<float>()));
                }
            }
            if (!src._localPointFaceVaryingStencils.empty())
            {
                _localPointFaceVaryingStencils.Resize(src._localPointFaceVaryingStencils.Count);
                for (int fvc = 0; fvc < (int)_localPointFaceVaryingStencils.Count; ++fvc)
                {
                    if (src._localPointFaceVaryingStencils[fvc])
                    {
                        if (src._faceVaryingPrecisionIsDouble)
                        {
                            _localPointFaceVaryingStencils[fvc].Set(new StencilTableReal<double>(
                                src._localPointFaceVaryingStencils[fvc].Get<double>()));
                        }
                        else
                        {
                            _localPointFaceVaryingStencils[fvc].Set(new StencilTableReal<float>(
                                src._localPointFaceVaryingStencils[fvc].Get<float>()));
                        }
                    }
                }
            }
        }

        //  (the C++ destructor only deletes the stencil tables: nothing to do in C#)

        /// \brief True if the PatchTable contains feature-adaptive patches
        public bool IsFeatureAdaptive()
        {
            return !_isUniformLinear;
        }

        /// \brief Returns the total number of control vertex indices in the table
        public int GetNumControlVerticesTotal()
        {
            return (int)_patchVerts.Count;
        }

        /// \brief Returns the total number of patches stored in the table
        public int GetNumPatchesTotal()
        {
            return (int)_paramTable.Count;
        }

        /// \brief Returns max vertex valence
        public int GetMaxValence()
        {
            return _maxValence;
        }

        /// \brief Returns the total number of ptex faces in the mesh
        public int GetNumPtexFaces()
        {
            return _numPtexFaces;
        }

        //
        //  Individual patches
        //

        /// \brief Returns the PatchDescriptor for the patches in the array
        public PatchDescriptor GetPatchDescriptor(PatchHandle handle)
        {
            return getPatchArray(handle.arrayIndex).desc;
        }

        /// \brief Returns the control vertex indices for the patch identified by the handle
        public ConstIndexArray GetPatchVertices(PatchHandle handle)
        {
            PatchArray pa = getPatchArray(handle.arrayIndex);
            int vert = pa.vertIndex + handle.vertIndex;
            return new ConstIndexArray(_patchVerts.Data, vert, getPatchSize(pa.desc));
        }

        /// \brief Returns the PatchParam for the patch identified by the handle
        public PatchParam GetPatchParam(PatchHandle handle)
        {
            System.Diagnostics.Debug.Assert(handle.patchIndex < (int)_paramTable.Count);
            return _paramTable[handle.patchIndex];
        }

        /// \brief Returns the control vertex indices for the patch
        public ConstIndexArray GetPatchVertices(int arrayIndex, int patchIndex)
        {
            PatchArray pa = getPatchArray(arrayIndex);

            int size = getPatchSize(pa.desc);
            System.Diagnostics.Debug.Assert((pa.vertIndex + patchIndex * size) < (int)_patchVerts.Count);

            return new ConstIndexArray(_patchVerts.Data, pa.vertIndex + patchIndex * size, size);
        }

        /// \brief Returns the PatchParam for the patch
        public PatchParam GetPatchParam(int arrayIndex, int patchIndex)
        {
            PatchArray pa = getPatchArray(arrayIndex);

            System.Diagnostics.Debug.Assert((pa.patchIndex + patchIndex) < (int)_paramTable.Count);
            return _paramTable[pa.patchIndex + patchIndex];
        }

        //
        //  Arrays of patches
        //

        /// \brief Returns the number of patch arrays in the table
        public int GetNumPatchArrays()
        {
            return (int)_patchArrays.Count;
        }

        /// \brief Returns the number of patches in patch array 'arrayIndex'
        public int GetNumPatches(int arrayIndex)
        {
            return getPatchArray(arrayIndex).numPatches;
        }

        /// \brief Returns the number of control vertices in patch array 'arrayIndex'
        public int GetNumControlVertices(int arrayIndex)
        {
            PatchArray pa = getPatchArray(arrayIndex);
            return pa.numPatches * getPatchSize(pa.desc);
        }

        /// \brief Returns the PatchDescriptor for the patches in array 'arrayIndex'
        public PatchDescriptor GetPatchArrayDescriptor(int arrayIndex)
        {
            return getPatchArray(arrayIndex).desc;
        }

        /// \brief Returns the control vertex indices for the patches in array 'arrayIndex'
        public ConstIndexArray GetPatchArrayVertices(int arrayIndex)
        {
            PatchArray pa = getPatchArray(arrayIndex);

            int size = getPatchSize(pa.desc);
            System.Diagnostics.Debug.Assert(pa.vertIndex < (int)_patchVerts.Count);

            return new ConstIndexArray(_patchVerts.Data, pa.vertIndex, pa.numPatches * size);
        }

        /// \brief Returns the PatchParams for the patches in array 'arrayIndex'
        public ConstPatchParamArray GetPatchParams(int arrayIndex)
        {
            PatchArray pa = getPatchArray(arrayIndex);

            return new ConstPatchParamArray(_paramTable.Data, pa.patchIndex, pa.numPatches);
        }

