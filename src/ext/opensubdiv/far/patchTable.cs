        /// \brief Returns the crease sharpness for the patch identified by handle
        public float GetSingleCreasePatchSharpnessValue(PatchHandle handle)
        {
            System.Diagnostics.Debug.Assert((handle.patchIndex) < (int)_sharpnessIndices.Count);

            int index = _sharpnessIndices[handle.patchIndex];
            if (index == FarTypes.INDEX_INVALID)
            {
                return 0.0f;
            }
            System.Diagnostics.Debug.Assert(index < (int)_sharpnessValues.Count);
            return _sharpnessValues[index];
        }

        /// \brief Returns the crease sharpness for the patch
        public float GetSingleCreasePatchSharpnessValue(int arrayIndex, int patchIndex)
        {
            PatchArray pa = getPatchArray(arrayIndex);

            System.Diagnostics.Debug.Assert((pa.patchIndex + patchIndex) < (int)_sharpnessIndices.Count);

            int index = _sharpnessIndices[pa.patchIndex + patchIndex];
            if (index == FarTypes.INDEX_INVALID)
            {
                return 0.0f;
            }
            System.Diagnostics.Debug.Assert(index < (int)_sharpnessValues.Count);
            return _sharpnessValues[index];
        }

