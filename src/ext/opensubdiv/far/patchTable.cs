        /// \brief Returns the number of local points for face-varying channel in the table
        public int GetNumLocalPointsFaceVarying(int channel = 0)
        {
            if (channel >= 0 && channel < (int)_localPointFaceVaryingStencils.Count)
            {
                if (!_localPointFaceVaryingStencils[channel])
                {
                    return 0;
                }
                return _faceVaryingPrecisionIsDouble
                    ? _localPointFaceVaryingStencils[channel].Get<double>().GetNumStencils()
                    : _localPointFaceVaryingStencils[channel].Get<float>().GetNumStencils();
            }
            return 0;
        }

        /// \brief Returns the stencil table to compute local point face-varying values
        public StencilTable GetLocalPointFaceVaryingStencilTable(int channel = 0)
        {
            System.Diagnostics.Debug.Assert(LocalPointFaceVaryingStencilPrecisionMatchesType<float>());
            if (channel >= 0 && channel < (int)_localPointFaceVaryingStencils.Count)
            {
                StencilTableReal<float> table = _localPointFaceVaryingStencils[channel].Get<float>();
                return (table == null) ? null : new StencilTable(table);
            }
            return null;
        }

        /// \brief Returns the stencil table to compute local point face-varying values
        public StencilTableReal<REAL> GetLocalPointFaceVaryingStencilTable<REAL>(int channel = 0) where REAL : unmanaged, System.Numerics.INumber<REAL>
        {
            System.Diagnostics.Debug.Assert(LocalPointFaceVaryingStencilPrecisionMatchesType<REAL>());
            if (channel >= 0 && channel < (int)_localPointFaceVaryingStencils.Count)
            {
                return _localPointFaceVaryingStencils[channel].Get<REAL>();
            }
            return null;
        }

        public bool LocalPointFaceVaryingStencilPrecisionMatchesType<REAL>()
        {
