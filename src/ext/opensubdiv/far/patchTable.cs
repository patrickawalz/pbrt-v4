        /// \brief Evaluate face-varying basis functions
        public void EvaluateBasisFaceVarying(PatchHandle handle, float s, float t,
            float[] wP, float[] wDs = null, float[] wDt = null,
            float[] wDss = null, float[] wDst = null, float[] wDtt = null,
            int channel = 0)
        {
            PatchParam param = getPatchFVarPatchParam(handle.patchIndex, channel);
            PatchDescriptor.Type patchType = param.IsRegular()
                ? GetFVarPatchDescriptorRegular(channel).GetType()
