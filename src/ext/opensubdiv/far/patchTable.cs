        public struct StencilTablePtr
        {
            private object _ptr;

            public StencilTablePtr(StencilTableReal<float> ptr)
            {
                _ptr = ptr;
            }

            public StencilTablePtr(StencilTableReal<double> ptr)
            {
                _ptr = ptr;
            }

            public static implicit operator bool(StencilTablePtr p)
            {
                return p._ptr != null;
            }

            //  C# addition: construct from a table whose precision is a generic argument
            public static StencilTablePtr From<REAL>(StencilTableReal<REAL> ptr) where REAL : unmanaged, System.Numerics.INumber<REAL>
            {
                StencilTablePtr result = new StencilTablePtr();
                result._ptr = ptr;
                return result;
            }

            public void Set()
            {
                _ptr = null;
            }

            public void Set(StencilTableReal<float> ptr)
            {
                _ptr = ptr;
            }

            public void Set(StencilTableReal<double> ptr)
            {
                _ptr = ptr;
            }

            public StencilTableReal<REAL> Get<REAL>() where REAL : unmanaged, System.Numerics.INumber<REAL>
            {
                return _ptr as StencilTableReal<REAL>;
            }
        }

