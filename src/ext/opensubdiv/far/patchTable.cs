        public struct PatchArray
        {
            public PatchArray(PatchDescriptor d, int np, int v, int p, int qo)
            {
                desc = d;
                numPatches = np;
                vertIndex = v;
                patchIndex = p;
                quadOffsetIndex = qo;
            }

            public void print()
            {
                desc.print();
                Console.Write("    numPatches={0} vertIndex={1} patchIndex={2} " +
                    "quadOffsetIndex={3}\n", numPatches, vertIndex, patchIndex,
                        quadOffsetIndex);
            }

            public PatchDescriptor desc; // type of patches in the array
            public int numPatches;       // number of patches in the array
            public int vertIndex,        // index to the first control vertex
                       patchIndex,       // absolute index of the first patch in the array
                       quadOffsetIndex;  // index of the first quad offset entry
        }

        public ref PatchArray getPatchArray(int arrayIndex)
        {
            System.Diagnostics.Debug.Assert(arrayIndex < (int)GetNumPatchArrays());
            return ref _patchArrays.Data[arrayIndex];
        }

        public void reservePatchArrays(int numPatchArrays)
        {
            _patchArrays.Reserve(numPatchArrays);
        }

        //  vidx, pidx and qoidx are in/out; the C++ qoidx pointer may be NULL (pass a null array --
        //  here modeled with a bool: hasQuadOffsetIndex)
        public void pushPatchArray(PatchDescriptor desc, int npatches,
            ref int vidx, ref int pidx)
        {
            if (npatches > 0)
            {
                _patchArrays.PushBack(new PatchArray(
                    desc, npatches, vidx, pidx, 0));

                int nverts = getPatchSize(desc);
                vidx += npatches * nverts;
                pidx += npatches;
            }
        }

        public void pushPatchArray(PatchDescriptor desc, int npatches,
            ref int vidx, ref int pidx, ref int qoidx)
        {
            if (npatches > 0)
            {
                _patchArrays.PushBack(new PatchArray(
                    desc, npatches, vidx, pidx, qoidx));

                int nverts = getPatchSize(desc);
                vidx += npatches * nverts;
                pidx += npatches;
                qoidx += (desc.GetType() == PatchDescriptor.Type.GREGORY) ?
                    npatches * nverts : 0;
            }
        }

        public IndexArray getPatchArrayVertices(int arrayIndex)
        {
            PatchArray pa = getPatchArray(arrayIndex);

            int size = getPatchSize(pa.desc);
            System.Diagnostics.Debug.Assert(pa.vertIndex < (int)_patchVerts.Count);

            return new IndexArray(_patchVerts.Data, pa.vertIndex, pa.numPatches * size);
        }

        public int findPatchArray(PatchDescriptor desc)
        {
            for (int i = 0; i < (int)_patchArrays.Count; ++i)
            {
                if (_patchArrays[i].desc == desc)
                {
                    return i;
                }
            }
            return FarTypes.INDEX_INVALID;
        }

        //
        //  Varying patch arrays
        //
        public IndexArray getPatchArrayVaryingVertices(int arrayIndex)
        {
            PatchArray pa = getPatchArray(arrayIndex);

            int numVaryingCVs = _varyingDesc.GetNumControlVertices();
            int start = pa.patchIndex * numVaryingCVs;
            return new IndexArray(_varyingVerts.Data, start, pa.numPatches * numVaryingCVs);
        }

        public void allocateVaryingVertices(
            PatchDescriptor desc, int numPatches)
        {
            _varyingDesc = desc;
            _varyingVerts.Resize(numPatches * desc.GetNumControlVertices());
        }

        public void populateVaryingVertices()
        {
            int numVaryingCVs = _varyingDesc.GetNumControlVertices();

            for (int arrayIndex = 0; arrayIndex < (int)_patchArrays.Count; ++arrayIndex)
            {
                PatchArray pa = getPatchArray(arrayIndex);

                PatchDescriptor.Type patchType = pa.desc.GetType();

                for (int patch = 0; patch < pa.numPatches; ++patch)
                {
                    ConstIndexArray vertexCVs = GetPatchVertices(arrayIndex, patch);

                    int start = (pa.patchIndex + patch) * numVaryingCVs;

                    if (patchType == PatchDescriptor.Type.REGULAR)
                    {
                        _varyingVerts[start + 0] = vertexCVs[5];
                        _varyingVerts[start + 1] = vertexCVs[6];
                        _varyingVerts[start + 2] = vertexCVs[10];
                        _varyingVerts[start + 3] = vertexCVs[9];
                    }
                    else if (patchType == PatchDescriptor.Type.GREGORY_BASIS)
                    {
                        _varyingVerts[start + 0] = vertexCVs[0];
                        _varyingVerts[start + 1] = vertexCVs[5];
                        _varyingVerts[start + 2] = vertexCVs[10];
                        _varyingVerts[start + 3] = vertexCVs[15];
                    }
                    else if (patchType == PatchDescriptor.Type.QUADS)
                    {
                        _varyingVerts[start + 0] = vertexCVs[0];
                        _varyingVerts[start + 1] = vertexCVs[1];
                        _varyingVerts[start + 2] = vertexCVs[2];
                        _varyingVerts[start + 3] = vertexCVs[3];
                    }
                    else if (patchType == PatchDescriptor.Type.TRIANGLES)
                    {
                        _varyingVerts[start + 0] = vertexCVs[0];
                        _varyingVerts[start + 1] = vertexCVs[1];
                        _varyingVerts[start + 2] = vertexCVs[2];
                    }
                }
            }
        }

