        /// \brief Returns the number of local points in the table
        public int GetNumLocalPoints()
        {
            if (!_localPointStencils)
            {
                return 0;
            }
            return _vertexPrecisionIsDouble
                ? _localPointStencils.Get<double>().GetNumStencils()
                : _localPointStencils.Get<float>().GetNumStencils();
        }

        /// \brief Returns the stencil table to compute local point vertex values
        public StencilTable GetLocalPointStencilTable()
        {
            System.Diagnostics.Debug.Assert(LocalPointStencilPrecisionMatchesType<float>());
            //  (C++ reinterpret_cast<StencilTable const *>: the C# StencilTable wraps the float table)
            StencilTableReal<float> table = _localPointStencils.Get<float>();
            return (table == null) ? null : new StencilTable(table);
        }

        /// \brief Returns the stencil table to compute local point vertex values
        public StencilTableReal<REAL> GetLocalPointStencilTable<REAL>() where REAL : unmanaged, System.Numerics.INumber<REAL>
        {
            System.Diagnostics.Debug.Assert(LocalPointStencilPrecisionMatchesType<REAL>());
            return _localPointStencils.Get<REAL>();
        }

        /// \brief Returns true if the precision of the local point stencil table matches REAL
        public bool LocalPointStencilPrecisionMatchesType<REAL>()
        {
            if (typeof(REAL) == typeof(float))
            {
                return !_vertexPrecisionIsDouble;
            }
            return _vertexPrecisionIsDouble;
        }

        /// \brief Updates local point values based on the control values
        public void ComputeLocalPointValues<T>(T[] src, T[] dst) where T : IPrimvar<T, float>
        {
            System.Diagnostics.Debug.Assert(LocalPointStencilPrecisionMatchesType<float>());
            if (_localPointStencils)
            {
                _localPointStencils.Get<float>().UpdateValues(src, dst);
            }
        }

        /// \brief Returns the number of local points for varying channel in the table
        public int GetNumLocalPointsVarying()
        {
            if (!_localPointVaryingStencils)
            {
                return 0;
            }
            return _varyingPrecisionIsDouble
                ? _localPointVaryingStencils.Get<double>().GetNumStencils()
                : _localPointVaryingStencils.Get<float>().GetNumStencils();
        }

        /// \brief Returns the stencil table to compute local point varying values
        public StencilTable GetLocalPointVaryingStencilTable()
