        /// \brief Returns the varying vertex indices for the patch identified by handle
        public ConstIndexArray GetPatchVaryingVertices(PatchHandle handle)
        {
            if (_varyingVerts.empty())
            {
                return new ConstIndexArray(null, 0, 0);
            }
            int numVaryingCVs = _varyingDesc.GetNumControlVertices();
            int start = handle.patchIndex * numVaryingCVs;
            return new ConstIndexArray(_varyingVerts.Data, start, numVaryingCVs);
        }

        /// \brief Returns the varying vertex indices for the patch
        public ConstIndexArray GetPatchVaryingVertices(int array, int patch)
        {
            if (_varyingVerts.empty())
            {
                return new ConstIndexArray(null, 0, 0);
            }
            PatchArray pa = getPatchArray(array);
            int numVaryingCVs = _varyingDesc.GetNumControlVertices();
            int start = (pa.patchIndex + patch) * numVaryingCVs;
            return new ConstIndexArray(_varyingVerts.Data, start, numVaryingCVs);
        }

        /// \brief Returns the varying vertex indices for the patches in array
        public ConstIndexArray GetPatchArrayVaryingVertices(int array)
        {
            if (_varyingVerts.empty())
            {
                return new ConstIndexArray(null, 0, 0);
            }
            PatchArray pa = getPatchArray(array);
            int numVaryingCVs = _varyingDesc.GetNumControlVertices();
            int start = pa.patchIndex * numVaryingCVs;
            int count = pa.numPatches * numVaryingCVs;
            return new ConstIndexArray(_varyingVerts.Data, start, count);
        }

        /// \brief Returns the varying vertex indices for all patches
        public ConstIndexArray GetVaryingVertices()
        {
            if (_varyingVerts.empty())
            {
                return new ConstIndexArray(null, 0, 0);
            }
            return new ConstIndexArray(_varyingVerts.Data, 0, (int)_varyingVerts.Count);
        }

