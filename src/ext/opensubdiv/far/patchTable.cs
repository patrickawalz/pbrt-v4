        public class FVarPatchChannel
        {
            public FVarPatchChannel()
            {
                interpolation = default(Options.FVarLinearInterpolation);
                regDesc = default(PatchDescriptor);
                irregDesc = default(PatchDescriptor);
                stride = 0;
                patchValues = new StdVector<int>();
                patchParam = new StdVector<PatchParam>();
            }

            //  Copy (the implicit C++ copy constructor)
            public FVarPatchChannel(FVarPatchChannel src)
            {
                interpolation = src.interpolation;
                regDesc = src.regDesc;
                irregDesc = src.irregDesc;
                stride = src.stride;
                patchValues = new StdVector<int>(src.patchValues);
                patchParam = new StdVector<PatchParam>(src.patchParam);
            }

            public Options.FVarLinearInterpolation interpolation;
            public PatchDescriptor regDesc;
            public PatchDescriptor irregDesc;
            public int stride;
            public StdVector<int> patchValues;
            public StdVector<PatchParam> patchParam;
        }

        public FVarPatchChannel getFVarPatchChannel(int channel)
        {
            System.Diagnostics.Debug.Assert(channel >= 0 && channel < (int)_fvarChannels.Count);
            return _fvarChannels[channel];
        }

        public void allocateFVarPatchChannels(int numChannels)
        {
            //  (std::vector::resize value-initializes new elements: create each channel)
            int oldCount = _fvarChannels.Count;
            _fvarChannels.Resize(numChannels);
            for (int i = oldCount; i < numChannels; ++i)
            {
                _fvarChannels[i] = new FVarPatchChannel();
            }
        }

        public void allocateFVarPatchChannelValues(
            PatchDescriptor regDesc, PatchDescriptor irregDesc,
            int numPatches, int channel)
        {
            FVarPatchChannel c = getFVarPatchChannel(channel);

            c.regDesc = regDesc;
            c.irregDesc = irregDesc;
            c.stride = Math.Max(regDesc.GetNumControlVertices(),
                                irregDesc.GetNumControlVertices());

            c.patchValues.Resize(numPatches * c.stride);
            c.patchParam.Resize(numPatches);
        }

        public void setFVarPatchChannelLinearInterpolation(
            Options.FVarLinearInterpolation interpolation, int channel)
        {
            FVarPatchChannel c = getFVarPatchChannel(channel);
            c.interpolation = interpolation;
        }

        public IndexArray getFVarValues(int channel)
        {
            FVarPatchChannel c = getFVarPatchChannel(channel);
            return new IndexArray(c.patchValues.Data, 0, (int)c.patchValues.Count);
        }

        public ConstIndexArray getPatchFVarValues(int patch, int channel)
        {
            FVarPatchChannel c = getFVarPatchChannel(channel);

            int ncvsThisPatch = c.patchParam[patch].IsRegular()
                ? c.regDesc.GetNumControlVertices()
                : c.irregDesc.GetNumControlVertices();

            return new ConstIndexArray(c.patchValues.Data, patch * c.stride, ncvsThisPatch);
        }

        public PatchParamArray getFVarPatchParams(int channel)
        {
            FVarPatchChannel c = getFVarPatchChannel(channel);
            return new PatchParamArray(c.patchParam.Data, 0, (int)c.patchParam.Count);
        }

        public PatchParam getPatchFVarPatchParam(int patch, int channel)
        {
            FVarPatchChannel c = getFVarPatchChannel(channel);
            return c.patchParam[patch];
        }

        //  C++ inline free function getPatchSize(PatchDescriptor)
        public static int getPatchSize(PatchDescriptor desc)
